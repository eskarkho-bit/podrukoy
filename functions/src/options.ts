import { setGlobalOptions } from 'firebase-functions/v2';

// Общие настройки функций. Файл импортируется в index.ts первым — раньше
// любого модуля с функциями: firebase-functions читает глобальные настройки в
// момент объявления функции, и всё, что объявлено до вызова setGlobalOptions,
// уезжает в бой без них. Так и было: реэкспорты стояли выше вызова, и
// четырнадцать функций из двадцати двух жили без потолка инстансов.
//
// Потолок инстансов — страховка от неожиданного счёта: всплеск заявок не
// должен превращаться в неограниченную рассылку.
setGlobalOptions({ maxInstances: 10 });
