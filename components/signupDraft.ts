// Что человек указал при регистрации до того, как у него появился uid.
//
// Профиль в базе создаётся уже после входа: правила разрешают запись только
// владельцу, а владельца до регистрации не существует. Между экраном
// регистрации и созданием профиля эти данные негде держать, кроме как здесь.
//
// Тот же приём, что и с согласиями в legal.ts, но отдельно: там документы,
// здесь профиль.

export type SignupDraft = {
  /** Ключ населённого пункта — им сравниваются заявки и мастера */
  city: string;
  /** Улица и дом. Показывается мастеру, когда он берётся за заявку. */
  address: string;
  /**
   * Имя — только при регистрации по телефону: у такого аккаунта нет
   * displayName, и взять имя при создании профиля больше неоткуда.
   */
  name?: string;
};

let pending: SignupDraft | null = null;

export function rememberSignup(draft: SignupDraft) {
  pending = draft;
}

/**
 * Отдаёт сохранённое ровно один раз.
 *
 * Второй вызов вернёт null: иначе адрес прилип бы к следующему аккаунту,
 * зарегистрированному на том же устройстве.
 */
export function takeSignupDraft(): SignupDraft | null {
  const value = pending;
  pending = null;
  return value;
}
