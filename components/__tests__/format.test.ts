import { counted, plural, ratingText, rub } from '../format';

// Склонения по числу — то место, где ошибка не ломает приложение, но делает
// интерфейс похожим на машинный перевод. Проверяем именно граничные случаи
// русской грамматики, а не «работает ли функция вообще».

describe('plural', () => {
  const word = (n: number) => plural(n, 'отзыв', 'отзыва', 'отзывов');

  test('единственное число', () => {
    expect(word(1)).toBe('отзыв');
    expect(word(21)).toBe('отзыв');
    expect(word(101)).toBe('отзыв');
  });

  test('от двух до четырёх', () => {
    expect(word(2)).toBe('отзыва');
    expect(word(3)).toBe('отзыва');
    expect(word(4)).toBe('отзыва');
    expect(word(22)).toBe('отзыва');
    expect(word(104)).toBe('отзыва');
  });

  test('множественное', () => {
    expect(word(0)).toBe('отзывов');
    expect(word(5)).toBe('отзывов');
    expect(word(9)).toBe('отзывов');
    expect(word(100)).toBe('отзывов');
  });

  // Одиннадцать-четырнадцать — исключение, на котором ломается наивная
  // реализация «по последней цифре»
  test('подростковые числа — исключение', () => {
    expect(word(11)).toBe('отзывов');
    expect(word(12)).toBe('отзывов');
    expect(word(13)).toBe('отзывов');
    expect(word(14)).toBe('отзывов');
    expect(word(111)).toBe('отзывов');
    expect(word(112)).toBe('отзывов');
  });
});

describe('counted', () => {
  test('число вместе со склонённым словом', () => {
    expect(counted(1, 'предложение', 'предложения', 'предложений'))
      .toBe('1 предложение');
    expect(counted(3, 'предложение', 'предложения', 'предложений'))
      .toBe('3 предложения');
    expect(counted(11, 'предложение', 'предложения', 'предложений'))
      .toBe('11 предложений');
  });
});

describe('rub', () => {
  test('разряды разделены, знак валюты на месте', () => {
    // Пробел здесь неразрывный — его ставит Intl, и обычный пробел тут
    // не совпадёт
    expect(rub(3500)).toMatch(/^3\s500\s₽$/u);
    expect(rub(0)).toBe('0 ₽');
  });

  test('миллионы не теряют разряды', () => {
    expect(rub(1234567)).toMatch(/^1\s234\s567\s₽$/u);
  });
});

describe('ratingText', () => {
  // Сюда приходит уже округлённое значение: агрегат считает функция как
  // Math.round(среднее * 10) / 10. Поэтому проверяем то, что бывает на деле.
  test('одна цифра после запятой, разделитель — запятая', () => {
    expect(ratingText(4.8)).toBe('4,8');
    expect(ratingText(5)).toBe('5,0');
    expect(ratingText(4)).toBe('4,0');
    expect(ratingText(3.5)).toBe('3,5');
  });

  // Половина в двоичной плавающей точке представима не всегда: 4.85 хранится
  // чуть меньше себя, и toFixed округляет вниз. На рейтинг это не влияет —
  // такие значения сюда не доходят, — но пусть поведение будет записано, а
  // не обнаружено однажды в споре с мастером.
  test('серединные значения округляются вниз, а не вверх', () => {
    expect(ratingText(4.85)).toBe('4,8');
    expect(ratingText(4.25)).toBe('4,3');
  });
});
