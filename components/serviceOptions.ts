// Запасной сценарий для объектов без собственного дерева
const DEFAULT_FLOW: ServiceType[] = [
  { label: 'Не работает', icon: '⚡', subs: ['Мелкий ремонт', 'Диагностика'] },
  { label: 'Замена', icon: '🔄', subs: ['Полная замена', 'Частичная'] },
  { label: 'Установка', icon: '🛠️', subs: ['Новая установка', 'Дополнительная'] },
];

// Запасной выход на каждом шаге: готовый список никогда не покроет все
// случаи, поэтому человек без подходящего пункта не должен упираться в тупик.
export const OTHER_LABEL = 'Другое';

export function flowFor(objectId: string): ServiceType[] {
  const flow = SERVICE_FLOWS[objectId] ?? DEFAULT_FLOW;
  // «Другое» добавляется здесь, а не в данных: так гарантия распространяется
  // на все деревья разом, включая запасное и будущие. Пустые subs — знак
  // шторке вести сразу к описанию и фото, минуя шаг уточнения.
  return [
    ...flow.map((t) => ({ ...t, subs: [...t.subs, OTHER_LABEL] })),
    { label: OTHER_LABEL, icon: '💬', subs: [] },
  ];
}

