export const LEGAL_DOCS: Record<LegalDocId, LegalDoc> = {
  terms: TERMS,
  privacy: PRIVACY,
  biometrics: BIOMETRICS,
};

/** Документы, без принятия которых сервисом пользоваться нельзя. */
export const REQUIRED_DOCS: LegalDocId[] = ['terms', 'privacy'];

export type Consents = Partial<Record<LegalDocId, string>>;

/** Приняты ли действующие редакции обязательных документов. */
export function consentsCurrent(consents: Consents | null | undefined): boolean {
  if (!consents) return false;
  return REQUIRED_DOCS.every((id) => consents[id] === LEGAL_DOCS[id].version);
}

/** Согласия для записи в профиль — по действующим на сейчас редакциям. */
export function currentConsents(): Consents {
  const out: Consents = {};
  REQUIRED_DOCS.forEach((id) => { out[id] = LEGAL_DOCS[id].version; });
  return out;
}

// Согласие даётся на экране регистрации, а профиль в базе создаётся уже после
// входа, когда появился uid. Между этими двумя моментами его негде держать,
// кроме как здесь.
let pending: Consents | null = null;

export function rememberConsent(consents: Consents) {
  pending = consents;
}

export function takePendingConsent(): Consents | null {
  const value = pending;
  pending = null;
  return value;
}
