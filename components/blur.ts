import { Platform } from 'react-native';

// Как размывать фон под шторками. На iOS размытие даёт система и стоит
// дёшево. На Android expo-blur каждый кадр делает снимок всего экрана и
// размывает его программно — под выезжающей пружиной шторкой это гарантированно
// роняет кадры на слабых телефонах. Там остаётся только затемнение: слой
// dim под шторкой и так есть у каждой из них.
export const BLUR_METHOD = Platform.OS === 'android' ? 'none' : 'dimezisBlurView';
